import { cutTiles } from './strips.js';

// =============================================================================
// Drawing an area's old core only near the cat (bigger areas, step 2: "the
// 65 m approach", docs/superpowers/specs/2026-11-19-bigger-areas-design.md).
//
// With the switch on (src/grow.js), everything SCATTERED in an area, its
// frozen core as well as its strips, is drawn only within a layer's range of
// the cat (world/strips.js LAYERS), and each tree past its range is a cheap
// far stand-in (render/standins.js). So what is on screen depends on the view
// range, not on how big the map is.
//
// The core is not rebuilt for this. Its scatter loops, their random draws,
// every collider, Sure Claws fork, perch, hide, rest and critter are exactly
// what they are with the switch off, built at the same moment in the same
// order. The area only TAGS what may stream; the walk does the rest after its
// caster sweep, contact-shadow scan and prop merge (render/striptiles.js):
//
//   * a tagged tree (a top-level Group) stays in the scene where it is; it is
//     made visible when its tile's trees layer comes into range and hidden
//     when it goes, with the stand-in shown in its place;
//   * a tagged merged scatter mesh is cut into one mesh per tile
//     (render/tilesplit.js: every triangle copied bit for bit to the tile its
//     item stands on), and each piece is shown and hidden by the small layer.
//
// -----------------------------------------------------------------------------
// HOW TO STREAM AN AREA (for the area agents: Woods, Pines, Moor, River south)
// -----------------------------------------------------------------------------
//
// Touch ONLY your area's own files (world/<area>.js, its dressing module, its
// strip module if it has one, and your own tests). Do not edit this file,
// world/strips.js, render/striptiles.js, render/tilesplit.js,
// render/standins.js, game/walk.js, main.js or test/helpers/growbudget.js; if
// you need a change there, say so in your report instead.
//
// In your area's build(), only when growOn() is true, AFTER everything of the
// core is built (so no draw or object moves):
//
//   1. For each scattered tree Group you added to the scene (not a landmark, a
//      climb chain's tree, a camp's tree or anything named or looked up),
//      call streamTree(group).
//   2. For each merged mesh of small scatter (reeds, ferns, tussocks,
//      flowers, stones...), call streamSmall(mesh, items) with the list of
//      things it was built from: [{ x, z, r }], r how far one thing's own
//      parts reach from its centre (0 for a reed clump, a bush's radius).
//      Triangles that belong to no item (moss on a bridge) stay whole.
//      Leave out anything flat and big (ground paint, path ribbons), anything
//      on the water a cat must see from afar, and anything gameplay reads.
//   3. Return the streams in the area's data:
//        strips: [...coreStreams({ areaId, rect: BOUNDS }), ...yourStrips]
//      The core's streams go FIRST. Your strips keep their own tiles (their
//      seeds hang on their indices); a strip's content(index) and
//      buildTree(tree) are as step 1 had them (world/riverwest.js is the
//      worked example), and its trees get stand-ins too.
//
// Then prove it with test/helpers/growbudget.js (worstSpot: the most the core
// and its strips can put on screen at once, at each layer's `hide` range) and
// copy test/growcore.test.js's checks for your area: the tagged items are the
// switch-off build's, byte for byte, and the recorded walk still passes.
// =============================================================================

// The streams of an area's frozen core: its rectangle cut into strips.js
// tiles, 10 m for the trees and the small layer and 5 m for the fine one (a
// finer cut puts the range where it is meant to be: a layer's range is
// measured to a tile's nearest point, so a tile can hold things up to its
// diagonal further out). `prebuilt` tells render/striptiles.js the things are
// already in the scene. Spread them into the area's `strips`, first.
export const CORE_TILE = 10;
export const FINE_TILE = 5;
export function coreStreams({ areaId, rect }) {
  return Object.freeze([
    Object.freeze({ areaId, id: 'core', rect, tiles: cutTiles(rect, CORE_TILE), prebuilt: true, layerIds: Object.freeze(['small', 'trees']) }),
    Object.freeze({ areaId, id: 'core-fine', rect, tiles: cutTiles(rect, FINE_TILE), prebuilt: true, layerIds: Object.freeze(['fine']) }),
  ]);
}

// Tags a top-level tree Group to be drawn by the trees layer (and a stand-in
// past it).
export function streamTree(group) {
  group.userData.stream = 'trees';
  return group;
}

// Tags a merged mesh of small scatter to be drawn per tile by the small layer
// (or by `layer`: 'fine' for a dense, costly stand such as a reedbed, drawn in
// full only nearer still). `items`: [{ x, z, r? }]; `reach`: how far past r a
// triangle may lie from its item's centre and still be that item's.
export function streamSmall(mesh, items, { reach = 1.2, layer = 'small' } = {}) {
  mesh.userData.stream = 'small';
  mesh.userData.streamLayer = layer;
  mesh.userData.streamItems = items;
  mesh.userData.streamReach = reach;
  return mesh;
}
