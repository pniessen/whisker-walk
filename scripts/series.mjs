// The seal tool for the family's word set. Run by the owner (and by agents for
// everything but printing a code), never shipped.
//
//   npm run series:init                        a new content key + an empty vault
//   npm run series:code -- --label family      a family code, added to the vault
//        [--out FILE]                          write the code to FILE (mode 0600, never overwritten) and print only the path
//   npm run series:seal                        re-seal the set of today under the same key
//   node scripts/series.mjs verify             exit 1 when no code opens the vault or its digest is stale
//   node scripts/series.mjs check <dir>        exit 1 when the content key is in any file under <dir>
//
// The content key lives in ONE file outside the repo: ~/.config/whisker-walk/series-key
// (mode 0600; WW_SERIES_KEY_FILE changes the path). It is never printed. The vault
// is src/seriesvault.js (WW_SERIES_VAULT_FILE changes the path): ciphertext only.
// A family code is 5 words and 4 characters; the tool prints it only on request, to
// stdout or to the --out file, and keeps no copy.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { webcrypto } from 'node:crypto';
import { packSet } from '../src/seriespack.js';
import { sealVault, addWrap, plaintextDigest, toB64, fromB64 } from '../src/seriescrypto.js';
import { normalizeCode } from '../src/redeem.js';
import { WORDS, CODE_ALPHABET } from './make-code.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const subtle = webcrypto.subtle;
const randomBytes = (n) => webcrypto.getRandomValues(new Uint8Array(n));

export const defaultKeyFile = () => process.env.WW_SERIES_KEY_FILE || join(homedir(), '.config', 'whisker-walk', 'series-key');
export const defaultVaultFile = () => process.env.WW_SERIES_VAULT_FILE || resolve(HERE, '..', 'src', 'seriesvault.js');

// The family's set, read from its own file. Not a src/ import: only scripts and tests may.
async function familyPlaintext() {
  return packSet(await import('../src/clanwords.js'));
}

// A new family code: 5 words and 4 characters, about 55 bits.
export function inventFamilyCode(rand = randomBytes) {
  const pickFrom = (list) => {
    // rejection sampling: no modulo bias
    const limit = 256 - (256 % list.length);
    for (;;) {
      const [b] = rand(1);
      if (b < limit) return list[b % list.length];
    }
  };
  const words = Array.from({ length: 5 }, () => pickFrom(WORDS));
  let tail = '';
  for (let i = 0; i < 4; i++) tail += pickFrom([...CODE_ALPHABET]);
  return `${words.join('-')}-${tail}`;
}

const HEADER = `// GENERATED by scripts/series.mjs (npm run series:seal). Do not edit.
// The family's word set, sealed with AES-256-GCM: ciphertext only. A family code
// unwraps the content key, and the key opens the set (src/seriescrypto.js).
`;

function vaultSource(vault) {
  return `${HEADER}export const VAULT = Object.freeze(${JSON.stringify(vault, null, 2)});\n`;
}

async function readVault(file) {
  const mod = await import(`${pathToFileURL(file).href}?t=${Date.now()}${Math.random()}`);
  return mod.VAULT;
}

function readKey(keyFile) {
  if (!existsSync(keyFile)) throw new Error(`no key file at ${keyFile}: run npm run series:init`);
  const key = fromB64(readFileSync(keyFile, 'utf8').trim());
  if (key.length !== 32) throw new Error(`the key file ${keyFile} does not hold a 32-byte key`);
  return key;
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function parseFlags(args) {
  const flags = {};
  const rest = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i].startsWith('--')) flags[args[i].slice(2)] = args[++i];
    else rest.push(args[i]);
  }
  return { flags, rest };
}

// Runs one subcommand. `io` is { out(text), err(text) }; returns the exit code.
export async function runSeries(argv, { keyFile = defaultKeyFile(), vaultFile = defaultVaultFile(), io = { out: console.log, err: console.error } } = {}) {
  const [cmd, ...args] = argv;
  const { flags, rest } = parseFlags(args);
  try {
    if (cmd === 'init') {
      if (existsSync(keyFile)) {
        io.err(`${keyFile} already exists. A new key locks every family device out: remove it by hand only if that is what you want.`);
        return 1;
      }
      const key = randomBytes(32);
      mkdirSync(dirname(keyFile), { recursive: true });
      writeFileSync(keyFile, `${toB64(key)}\n`, { mode: 0o600 });
      const vault = await sealVault({ plaintext: await familyPlaintext(), contentKey: key, salt: randomBytes(16), wraps: [] }, subtle, randomBytes);
      writeFileSync(vaultFile, vaultSource(vault));
      io.out(`wrote the key to ${keyFile} (mode 0600) and an empty vault to ${vaultFile}. Next: series:code`);
      return 0;
    }
    if (cmd === 'code') {
      const id = flags.label;
      if (!id || !/^[a-z0-9-]{1,32}$/.test(id)) {
        io.err('give the code a label of lowercase letters, digits and dashes: --label family');
        return 1;
      }
      const key = readKey(keyFile);
      const vault = await readVault(vaultFile);
      const code = inventFamilyCode();
      const next = await addWrap(vault, { id, code: normalizeCode(code), contentKey: key }, subtle, randomBytes);
      if (flags.out) {
        if (existsSync(flags.out)) {
          io.err(`${flags.out} already exists: not overwritten, and nothing changed.`);
          return 1;
        }
        mkdirSync(dirname(flags.out), { recursive: true });
        writeFileSync(flags.out, `${code}\n`, { mode: 0o600, flag: 'wx' });
        io.out(`code "${id}" written to ${flags.out} (mode 0600); the vault has ${next.wraps.length} way(s) in. Commit src/seriesvault.js only.`);
      } else {
        io.out(`Family code "${id}" (shown once, keep it in the password manager and nowhere else):\n  ${code}`);
      }
      writeFileSync(vaultFile, vaultSource(next));
      return 0;
    }
    if (cmd === 'seal') {
      const key = readKey(keyFile);
      const old = await readVault(vaultFile);
      const fresh = await sealVault({ plaintext: await familyPlaintext(), contentKey: key, salt: fromB64(old.salt), wraps: [] }, subtle, randomBytes);
      writeFileSync(vaultFile, vaultSource({ ...fresh, wraps: old.wraps }));
      io.out(`sealed the family set again (${old.wraps.length} way(s) in).`);
      return 0;
    }
    if (cmd === 'verify') {
      const vault = await readVault(vaultFile);
      const inSync = vault.digest === await plaintextDigest(await familyPlaintext(), subtle);
      io.out(`wraps ${vault.wraps.length}, digest ${inSync ? 'in sync' : 'STALE: run npm run series:seal'}`);
      if (vault.wraps.length === 0) {
        io.err('no family code opens the vault: run npm run series:code');
        return 1;
      }
      return inSync ? 0 : 1;
    }
    if (cmd === 'check') {
      const dir = rest[0];
      if (!dir || !existsSync(dir)) {
        io.err('give a folder to check: node scripts/series.mjs check dist');
        return 1;
      }
      const key = readKey(keyFile);
      const b64 = toB64(key);
      const forms = [b64, b64.replace(/=+$/, ''), b64.replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, ''), Buffer.from(key).toString('hex')];
      const found = walk(dir).filter((f) => {
        const text = readFileSync(f).toString('latin1');
        return forms.some((x) => text.includes(x));
      });
      for (const f of found) io.err(`the content key is in ${f}`);
      if (found.length === 0) io.out(`the content key is in no file under ${dir}`);
      return found.length ? 1 : 0;
    }
    io.err('usage: series.mjs init | code --label ID [--out FILE] | seal | verify | check DIR');
    return 1;
  } catch (e) {
    io.err(`series ${cmd}: ${e.message}`);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(await runSeries(process.argv.slice(2)));
}
