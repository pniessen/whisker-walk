// `npm run headroom` (after `npm run build`): one table of how much room each
// size-guarded download has left. The numbers and ceilings come straight from
// scripts/buildjson.mjs (nothing is re-measured differently here).
// `--write` also saves the table to docs/headroom.md.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import * as B from './buildjson.mjs';

export const TIGHT_KB = 3;

export function statusOf(spare) {
  if (spare < 0) return 'OVER';
  return spare < TIGHT_KB ? 'TIGHT' : 'OK';
}

const row = (name, kb, ceiling) => ({ name, kb, ceiling, spare: ceiling - kb, status: statusOf(ceiling - kb) });

/**
 * Pure. data = { startKb, areas: {id: kb}, stages: {moon|reef|crystal|snowville|jungle: {part: kb, total: kb}} }
 * ceilings = { start, area, stage: {group: {each, total}} }. Returns rows in table order.
 */
export function buildRows(data, ceilings) {
  const rows = [row('start-up', data.startKb, ceilings.start)];
  for (const [group, parts] of Object.entries(data.stages)) {
    const c = ceilings.stage[group];
    for (const [part, kb] of Object.entries(parts)) {
      if (part === 'total') continue;
      rows.push(row(`${group} ${part === group ? 'A' : part.replace(group, '')}`, kb, c.each));
    }
    rows.push(row(`${group} (all stages)`, parts.total, c.total));
  }
  const staged = new Set(Object.keys(data.stages));
  const top = Object.entries(data.areas).filter(([id]) => !staged.has(id))
    .sort((a, b) => b[1] - a[1]).slice(0, 5);
  for (const [id, kb] of top) rows.push(row(`${id} (area)`, kb, ceilings.area));
  return rows;
}

export function formatTable(rows, markdown = false) {
  const f = (n) => n.toFixed(1);
  const head = ['name', 'gzip kB', 'ceiling kB', 'spare kB', 'status'];
  const body = rows.map((r) => [r.name, f(r.kb), f(r.ceiling), f(r.spare), r.status]);
  if (markdown) {
    return [`| ${head.join(' | ')} |`, '| --- | ---: | ---: | ---: | --- |', ...body.map((b) => `| ${b.join(' | ')} |`)].join('\n') + '\n';
  }
  const w = head.map((h, i) => Math.max(h.length, ...body.map((b) => b[i].length)));
  const line = (cells) => cells.map((c, i) => (i === 0 || i === 4 ? c.padEnd(w[i]) : c.padStart(w[i]))).join('  ');
  return [line(head), w.map((n) => '-'.repeat(n)).join('  '), ...body.map(line)].join('\n') + '\n';
}

export const CEILINGS = {
  start: B.MAIN_GZIP_CEILING_KB,
  area: B.AREA_GZIP_CEILING_KB,
  stage: {
    moon: { each: B.MOON_STAGE_GZIP_CEILING_KB, total: B.MOON_TOTAL_GZIP_CEILING_KB },
    reef: { each: B.REEF_STAGE_GZIP_CEILING_KB, total: B.REEF_TOTAL_GZIP_CEILING_KB },
    crystal: { each: B.CRYSTAL_STAGE_GZIP_CEILING_KB, total: B.CRYSTAL_TOTAL_GZIP_CEILING_KB },
    snowville: { each: B.SNOWVILLE_STAGE_GZIP_CEILING_KB, total: B.SNOWVILLE_TOTAL_GZIP_CEILING_KB },
    jungle: { each: B.JUNGLE_STAGE_GZIP_CEILING_KB, total: B.JUNGLE_TOTAL_GZIP_CEILING_KB },
  },
};

export function measure(dir) {
  const manifest = JSON.parse(readFileSync(join(dir, '.vite', 'manifest.json'), 'utf8'));
  const kbOf = (fs) => fs.reduce((n, f) => n + gzipSync(readFileSync(join(dir, f))).length, 0) / 1000;
  const mapKb = (o) => Object.fromEntries(Object.entries(o).map(([id, fs]) => [id, kbOf(fs)]));
  return {
    startKb: kbOf(B.startupFiles(manifest)),
    areas: mapKb(B.areaDownloads(manifest)),
    stages: { moon: mapKb(B.moonDownloads(manifest)), reef: mapKb(B.reefDownloads(manifest)), crystal: mapKb(B.crystalDownloads(manifest)), snowville: mapKb(B.snowvilleDownloads(manifest)), jungle: mapKb(B.jungleDownloads(manifest)) },
  };
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const args = process.argv.slice(2);
  const dir = args.find((a) => !a.startsWith('--')) || 'dist';
  const rows = buildRows(measure(dir), CEILINGS);
  process.stdout.write(formatTable(rows));
  if (args.includes('--write')) {
    const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'headroom.md');
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, `# Size headroom\n\nGenerated by \`npm run headroom -- --write\` after a build. Gzip kB (1 kB = 1000 bytes); TIGHT means under ${TIGHT_KB} kB spare. Ceilings live in scripts/buildjson.mjs.\n\n${formatTable(rows, true)}`);
    console.log(`wrote ${out}`);
  }
}
